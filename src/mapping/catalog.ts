export const invoiceStatusMap: Record<string, { state: string; status: string }> = {
  DRAFT: { state: "Active", status: "New" },
  SUBMITTED: { state: "Active", status: "New" },
  AUTHORISED: { state: "Active", status: "Unpaid" },
  PART_PAID: { state: "Active", status: "Partial" },
  PAID: { state: "Closed", status: "Paid" },
  VOIDED: { state: "Canceled", status: "Canceled" },
  DELETED: { state: "Canceled", status: "Canceled" },
};

export function mapInvoiceStatus(status?: string) {
  return invoiceStatusMap[(status ?? "").toUpperCase()] ?? { state: "Active", status: status || "Unknown" };
}
